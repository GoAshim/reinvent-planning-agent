# Import libraries
from strands import Agent, tool
from strands.models import BedrockModel
from src.strands_tools import search_sessions, get_session_details, check_conflict
from src.bedrock_client import MODEL_ID, session
from src.memory import SQLiteShortTermMemory, SQLiteLongTermMemory
from phoenix.otel import register


# Initialize a OpenTelemetry pipeline / trace to the 
# local Phoenix server
tracer_provider = register(
    # This groups the traces in the Phoenix UI
    project_name="reinvent-agent-local" 
)


# Initialize a Bedrock model with the Haiku model id 
# and the SSO session defined in bedrock_client.py
model = BedrockModel(
    model_id=MODEL_ID,
    boto_session=session,
)

# Initialize the SQLite memory engine
st_memory = SQLiteShortTermMemory()
lt_memory = SQLiteLongTermMemory()

# Initialize tools array
tools = [
    search_sessions,
    get_session_details,
    check_conflict,
]
# Initialize system prompt
SYSTEM_PROMPT = """
    You are a helpful AWS re:Invent 2026 
    session planning assistant.
"""


def run_strands_agent(
    user_prompt: str,
    session_id: str,
) -> str:
    """
    Answer user prompt using this session's 
    history from SQLite database.
    """

    # Fetch the conversational history / short 
    # term memory from the database
    history = st_memory.get_context(session_id)
    history = [
        {
            "role": turn["role"],
            "content": [{
                "text": turn["content"]
            }]
        }
        for turn in history
    ]

    # Create an agent that starts with this 
    # session's history
    agent = Agent(
        model=model,
        tools=tools,
        system_prompt=SYSTEM_PROMPT,
        messages=history,
        callback_handler=None,  # Stop Strands printing the answer
    )

    # Run the agent loop on the new prompt
    response = agent(user_prompt)

    # Save the new conversation exchange back to 
    # the short term memory from the database
    st_memory.save_turn(session_id, user_prompt, str(response))

    return str(response)


def run_strands_agent_with_LTM(
    user_prompt: str,
    session_id: str,
    user_id: str,
) -> str:
    """
    Answer user prompt using this session's 
    history / short-term memory and user 
    preference / long-term memory from 
    SQLite database.
    """

    # Fetch the user preference / long-term memory
    user_profile = lt_memory.get_user_profile(user_id)
    # Append the system prompt with long-term memory, and
    # tell the model to use it as default search filters
    dynamic_system_prompt = SYSTEM_PROMPT
    if user_profile:
        dynamic_system_prompt += f"""
    {user_profile}
    Apply these preferences as default filters when you
    call search_sessions (for example, pass the preferred
    level as the level argument), unless the user asks
    for something different in this conversation. If no
    session matches the preferences, say so and offer to
    search without them.
    For preferences that search_sessions cannot filter on,
    such as venues to avoid, remove sessions that don't
    match from the results yourself before answering.
    """

    # Fetch the conversational history / short 
    # term memory from the database
    history = st_memory.get_context(session_id)
    history = [
        {
            "role": turn["role"],
            "content": [{
                "text": turn["content"]
            }]
        }
        for turn in history
    ]

    # Dynamically build the memory tool that the LLM 
    # will call to save user preference 
    @tool
    def save_user_preference(key: str, value: str) -> str:
        """
        Saves a durable fact or preference about the user into long-term memory.
        Call this autonomously whenever the user states a clear preference 
        (e.g., "I prefer level 300", "Avoid the MGM Grand", "I like Generative AI").
        
        :param key: A short, descriptive snake_case key (e.g., preferred_level, avoid_venue)
        :param value: The value of the preference (e.g., 300, MGM Grand)
        """
        # The tool uses the user_id passed into run_strands_agent_with_LTM
        # So it's not generated by the LLM
        lt_memory.set_preference(user_id, key, value)
        return f"System: Successfully saved {key}={value} to long-term memory."
    
    # Create an agent 
    agent = Agent(
        model=model,
        tools=tools + [save_user_preference],
        system_prompt=dynamic_system_prompt,
        messages=history,
        callback_handler=None,  # Stop Strands printing the answer
    )

    # Run the agent loop on the new prompt
    response = agent(user_prompt)

    # Save the new conversation exchange back to 
    # the short term memory from the database
    st_memory.save_turn(session_id, user_prompt, str(response))

    return str(response)
